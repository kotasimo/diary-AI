create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  handle text not null,
  location text default '',
  tagline text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.diary_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  entry_date date not null,
  title text not null default '無題',
  body text not null default '',
  distance_km numeric(6, 1) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, entry_date)
);

alter table public.profiles enable row level security;
alter table public.diary_entries enable row level security;

drop policy if exists "Profiles are visible to signed-in users" on public.profiles;
drop policy if exists "Users can insert their own profile" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles;
drop policy if exists "Diary entries are visible to signed-in users" on public.diary_entries;
drop policy if exists "Users can insert their own diary entries" on public.diary_entries;
drop policy if exists "Users can update their own diary entries" on public.diary_entries;
drop policy if exists "Users can delete their own diary entries" on public.diary_entries;

create policy "Profiles are visible to signed-in users"
  on public.profiles for select
  to authenticated
  using (true);

create policy "Users can insert their own profile"
  on public.profiles for insert
  to authenticated
  with check (auth.uid() = id);

create policy "Users can update their own profile"
  on public.profiles for update
  to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

create policy "Diary entries are visible to signed-in users"
  on public.diary_entries for select
  to authenticated
  using (true);

create policy "Users can insert their own diary entries"
  on public.diary_entries for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "Users can update their own diary entries"
  on public.diary_entries for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Users can delete their own diary entries"
  on public.diary_entries for delete
  to authenticated
  using (auth.uid() = user_id);
